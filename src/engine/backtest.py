import asyncio
import logging
from collections.abc import AsyncIterator

from engine.events import Event, MarketEvent

logger = logging.getLogger(__name__)

class BacktestEngine:
    """The core event loop that processes historical data bar-by-bar."""

    def __init__(self, data_iterator: AsyncIterator[MarketEvent]) -> None:
        self.data_iterator = data_iterator
        self.events_queue: asyncio.Queue[Event] = asyncio.Queue()

    async def run(self) -> None:
        """Main execution loop."""
        logger.info("Starting Backtest Engine...")
        
        # In a real system, you would have concurrent tasks for Strategy, Portfolio, and Execution.
        # For this boilerplate, we process sequentially for simplicity.
        async for market_event in self.data_iterator:
            await self.events_queue.put(market_event)
            
            # Process all events generated by this market bar
            while not self.events_queue.empty():
                event = await self.events_queue.get()
                await self._process_event(event)

        logger.info("Backtest Engine finished.")

    async def _process_event(self, event: Event) -> None:
        """Routes events to the appropriate handler."""
